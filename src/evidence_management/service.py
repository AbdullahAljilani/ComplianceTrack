"""Evidence Management logic.

Designed in Unit 3, left unbuilt in Unit 4, implemented here. The module holds
the rules for accepting a supporting document against a control, versioning it,
and putting it through reviewer approval.

As in the scoring service, the decisions are written as pure functions so they
can be tested without a database or a web request. The storage functions below
them call those decisions rather than repeating the rules inline.

Secure file handling is part of the logic, not a wrapper around it. A file the
user uploads is never trusted for its name, its extension alone or its size:
the stored name is generated by this module, the extension is checked against
an allowlist, the size is capped, and the bytes are hashed so the same document
cannot be filed twice against one control.
"""
import hashlib
import os
import re
from datetime import datetime, timezone

from src import db
from src.services import audit

ALLOWED_EXTENSIONS = {".pdf", ".png", ".jpg", ".jpeg", ".txt", ".csv",
                      ".docx", ".xlsx"}
MAX_UPLOAD_BYTES = 10 * 1024 * 1024          # 10 MB
PENDING, APPROVED, REJECTED = "Pending Review", "Approved", "Rejected"

_SAFE_LABEL = re.compile(r"[^A-Za-z0-9._-]")


# ---------------------------------------------------------------------------
# Section 1: pure decisions
# ---------------------------------------------------------------------------

def sha256_of(data: bytes) -> str:
    """Content digest. Used both as a duplicate check and as an integrity
    record, so a stored file can later be shown not to have changed."""
    return hashlib.sha256(data).hexdigest()


def sanitize_label(original_name: str) -> str:
    """Reduce a user-supplied filename to a safe display label.

    Any directory component is discarded before anything else, so a name such
    as '../../etc/passwd' cannot escape the evidence directory. What remains is
    restricted to letters, digits, dot, dash and underscore.
    """
    base = os.path.basename(str(original_name or "")).replace("\\", "/")
    base = base.rsplit("/", 1)[-1]
    base = _SAFE_LABEL.sub("_", base).lstrip(".")
    return (base or "unnamed")[:120]


def extension_of(original_name: str) -> str:
    return os.path.splitext(sanitize_label(original_name))[1].lower()


def validate_upload(original_name: str, data: bytes):
    """Return (True, None) if the upload may be accepted, else (False, reason).

    Checked in a fixed order so the message a user sees is the first thing
    actually wrong, not whichever rule happened to run last.
    """
    if not data:
        return False, "The uploaded file is empty."
    if len(data) > MAX_UPLOAD_BYTES:
        return False, (f"The file is larger than the "
                       f"{MAX_UPLOAD_BYTES // (1024 * 1024)} MB limit.")
    ext = extension_of(original_name)
    if ext not in ALLOWED_EXTENSIONS:
        return False, (f"'{ext or 'no extension'}' is not an accepted evidence "
                       f"format.")
    return True, None


def next_version(existing_versions) -> int:
    """Next version number in a control's evidence chain.

    Gaps are tolerated: the chain continues from the highest number used, never
    reusing one that has been issued. The database unique constraint on
    (control_id, version_no) is the backstop if two uploads race.
    """
    numbers = [int(v) for v in existing_versions if v is not None]
    return max(numbers) + 1 if numbers else 1


def stored_filename(control_id: int, version_no: int, original_name: str) -> str:
    """Path-safe name the file is written under.

    Built from values this module controls. The sanitised original is appended
    only so a human browsing the store can recognise the file; it can never
    introduce a separator or a parent reference.
    """
    return f"c{int(control_id):04d}_v{int(version_no):03d}_{sanitize_label(original_name)}"


def is_duplicate(new_hash: str, existing_hashes) -> bool:
    return new_hash in set(existing_hashes)


def can_review(uploader_id: int, reviewer_id: int) -> bool:
    """Separation of duties: nobody approves their own evidence.

    The Unit 3 design puts approval in the hands of a reviewer. Allowing the
    uploader to also be that reviewer would make the gate on the Implemented
    status meaningless, since one person could satisfy both halves of it.
    """
    return int(uploader_id) != int(reviewer_id)


def resolve_review(decision: str):
    """Map a submitted decision onto a stored status, or None if invalid."""
    return {"approve": APPROVED, "reject": REJECTED}.get(str(decision).lower())


# ---------------------------------------------------------------------------
# Section 2: storage, calling the decisions above
# ---------------------------------------------------------------------------

def evidence_root(app_config):
    path = app_config.get("EVIDENCE_ROOT")
    os.makedirs(path, exist_ok=True)
    return path


def list_for_control(control_id):
    return db.query(
        """
        SELECT e.evidence_id, e.file_name, e.version_no, e.status,
               e.sha256_hash, e.size_bytes, e.description, e.uploaded_at,
               e.reviewed_at, e.review_note,
               up.full_name AS uploaded_by_name, up.user_id AS uploaded_by,
               rv.full_name AS reviewed_by_name
        FROM evidence e
        JOIN users up ON up.user_id = e.uploaded_by
        LEFT JOIN users rv ON rv.user_id = e.reviewed_by
        WHERE e.control_id = %s
        ORDER BY e.version_no DESC
        """,
        (control_id,),
    )


def approved_count(control_id) -> int:
    return db.query_one(
        "SELECT COUNT(*) AS n FROM evidence WHERE control_id = %s AND status = %s",
        (control_id, APPROVED),
    )["n"]


def store_evidence(control_id, uploader_id, original_name, data, description,
                   storage_root):
    """Validate, version, hash and persist one evidence record.

    Returns (evidence_id, None) on success or (None, reason) on refusal. The
    database row and the audit entry are written in the same transaction as
    every other change in the request, so a failure later in the request cannot
    leave an orphaned record behind.
    """
    ok, reason = validate_upload(original_name, data)
    if not ok:
        return None, reason

    digest = sha256_of(data)
    existing = db.query(
        "SELECT version_no, sha256_hash FROM evidence WHERE control_id = %s",
        (control_id,),
    )
    if is_duplicate(digest, [r["sha256_hash"] for r in existing]):
        return None, ("That exact file is already filed against this control. "
                      "Upload a changed document to create a new version.")

    version = next_version([r["version_no"] for r in existing])
    safe_name = stored_filename(control_id, version, original_name)
    full_path = os.path.join(storage_root, safe_name)

    with open(full_path, "wb") as handle:
        handle.write(data)

    row = db.query_one(
        """
        INSERT INTO evidence (control_id, uploaded_by, file_name, storage_path,
                              sha256_hash, version_no, status, size_bytes,
                              description)
        VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s)
        RETURNING evidence_id
        """,
        (control_id, uploader_id, sanitize_label(original_name), full_path,
         digest, version, PENDING, len(data), (description or "").strip()[:500]),
    )
    audit.record("EVIDENCE_UPLOAD", "evidence", row["evidence_id"],
                 {"control_id": control_id, "version": version,
                  "sha256": digest[:16]})
    return row["evidence_id"], None


def review_evidence(evidence_id, reviewer_id, decision, note):
    """Approve or reject a pending record.

    Returns (True, message) or (False, reason). Rejecting the last approved
    record supporting a control that is recorded as Implemented moves that
    control to Evidence Missing, because the condition that justified the
    status no longer holds. Leaving it at Implemented would let the register
    assert something the evidence no longer supports.
    """
    new_status = resolve_review(decision)
    if new_status is None:
        return False, "That is not a valid review decision."

    record = db.query_one(
        """
        SELECT e.evidence_id, e.control_id, e.uploaded_by, e.status,
               e.version_no, c.status AS control_status, c.ecc_reference
        FROM evidence e JOIN controls c ON c.control_id = e.control_id
        WHERE e.evidence_id = %s
        """,
        (evidence_id,),
    )
    if record is None:
        return False, "That evidence record does not exist."
    if record["status"] != PENDING:
        return False, f"This record has already been {record['status'].lower()}."
    if not can_review(record["uploaded_by"], reviewer_id):
        return False, ("Evidence must be reviewed by someone other than the "
                       "person who uploaded it.")
    if new_status == REJECTED and len((note or "").strip()) < 10:
        return False, "A rejection must record a reason of at least 10 characters."

    db.execute(
        """
        UPDATE evidence
        SET status = %s, reviewed_by = %s, reviewed_at = %s, review_note = %s
        WHERE evidence_id = %s
        """,
        (new_status, reviewer_id, datetime.now(timezone.utc),
         (note or "").strip()[:500], evidence_id),
    )
    audit.record("EVIDENCE_REVIEW", "evidence", evidence_id,
                 {"control_id": record["control_id"], "decision": new_status})

    demoted = False
    if (new_status == REJECTED
            and record["control_status"] == "Implemented"
            and approved_count(record["control_id"]) == 0):
        db.execute(
            "UPDATE controls SET status = %s, updated_at = now() WHERE control_id = %s",
            ("Evidence Missing", record["control_id"]),
        )
        audit.record(audit.STATUS_CHANGE, "control", record["control_id"],
                     {"ecc_reference": record["ecc_reference"],
                      "from": "Implemented", "to": "Evidence Missing",
                      "reason": "last approved evidence rejected"})
        demoted = True

    message = f"Version {record['version_no']} {new_status.lower()}."
    if demoted:
        message += (" The control moved to Evidence Missing because no approved "
                    "evidence remains.")
    return True, message


def find_gate_violations():
    """Controls recorded as Implemented that hold no approved evidence.

    The gate in the Control Register runs on a status *transition*. It cannot
    see a row that arrived at Implemented some other way: a bulk import, a
    seeded dataset, or a direct database change. This query states the
    invariant over the whole register rather than over one change at a time,
    so a violation is visible instead of silently inflating the score.
    """
    return db.query(
        """
        SELECT c.control_id, c.ecc_reference, c.status
        FROM controls c
        LEFT JOIN v_control_evidence_coverage cov ON cov.control_id = c.control_id
        WHERE c.scope_tier = 'in_scope'
          AND c.status = 'Implemented'
          AND COALESCE(cov.approved_count, 0) = 0
        ORDER BY string_to_array(c.ecc_reference, '-')::int[]
        """
    )


def reconcile_evidence_gate(actor_id=None):
    """Move every violating control to Evidence Missing and log each move.

    Run as a maintenance pass rather than on every request, because it rewrites
    control records and each rewrite has to be attributable in the audit trail.
    Returns the list of controls that were changed.
    """
    violations = find_gate_violations()
    for row in violations:
        db.execute(
            "UPDATE controls SET status = %s, updated_at = now() WHERE control_id = %s",
            ("Evidence Missing", row["control_id"]),
        )
        audit.record(audit.STATUS_CHANGE, "control", row["control_id"],
                     {"ecc_reference": row["ecc_reference"],
                      "from": "Implemented", "to": "Evidence Missing",
                      "reason": "evidence gate reconciliation"},
                     user_id=actor_id)
    return violations
